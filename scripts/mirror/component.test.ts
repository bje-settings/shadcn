import { join } from 'node:path'
import { describe, expect, it } from 'vitest'
import {
  buildComponent,
  classProbe,
  dependenciesOf,
  markerSelectors,
  prepareComponent,
  sharedSlotOptions,
  type UpstreamItem,
} from './component.ts'
import { forStyle, parseConfig } from './config.ts'
import { compile, internalDefaults, root } from './test-support.ts'

const config = forStyle(
  parseConfig({
    namespace: 'bje',
    upstream: {
      url: 'https://example.com/{style}/{name}.json',
      colorsUrl: 'https://example.com/colors/{name}.json',
      styles: ['base-vega'],
    },
    theme: { baseColor: 'neutral', font: 'inter', iconLibrary: 'lucide' },
    components: ['badge'],
    typeset: {
      stylesheet: 'https://example.com/typeset.css',
      fixturesUrl: 'https://example.com/fixtures/{name}.ts',
      fixtures: [],
    },
    snapshotDir: 'upstream',
    outputDir: 'registry/{style}/ui',
    hooksDir: 'registry/{style}/hooks',
    globalsDir: 'registry/{style}/styles',
    harnessDir: 'ab/generated/{style}',
    registryFile: 'registry/{style}/registry.json',
    consumerClasses: [{ classes: ['border-b'], reason: 'consumer class' }],
  }),
  'base-vega',
)

const cssPath = join(root, 'upstream/base-vega/index.css')

async function build(item: UpstreamItem, compiler = compile) {
  const prepared = await prepareComponent(item, config, cssPath)
  const context = {
    slotOptions: {
      ...sharedSlotOptions(config, [prepared], internalDefaults),
      markers: markerSelectors([prepared], prepared),
    },
    types: new Map(),
    scaffolds: new Map(),
    external: new Map(),
  }
  return buildComponent(prepared, config, compiler, context)
}

const source = (classes: string) => `import { cva } from "class-variance-authority"
import { cn } from "cn"
const badgeVariants = cva("${classes}")
function Badge({ className }) {
  return <span data-slot="badge" className={cn(badgeVariants({ className }))} />
}
export { Badge }`

const badge = (content: string): UpstreamItem => ({
  name: 'badge',
  type: 'registry:ui',
  files: [{ path: 'registry/base-vega/ui/badge.tsx', type: 'registry:ui', content }],
})

describe('buildComponent', () => {
  it('writes the component and its module into a PascalCase folder', async () => {
    const result = await build(badge(source('group/badge inline-flex bg-primary')))
    expect(result.item).toEqual({
      name: 'badge',
      type: 'registry:ui',
      title: 'Badge',
      dependencies: ['clsx'],
      devDependencies: [
        '@testing-library/dom',
        '@testing-library/react',
        'jsdom',
        'sass',
        'vitest',
      ],
      registryDependencies: ['@bje/globals'],
      files: [
        { path: 'registry/vega/ui/Badge/Badge.tsx', type: 'registry:ui' },
        { path: 'registry/vega/ui/Badge/Badge.module.scss', type: 'registry:ui' },
        { path: 'registry/vega/ui/Badge/Badge.test.tsx', type: 'registry:ui' },
      ],
    })
    const [tsx, scss, test] = result.files
    expect(test?.content).toContain('describe("Badge", () => {')
    expect(tsx?.content).toMatch(
      /^\/\/ Generated by scripts\/mirror from shadcn base-vega\/badge\./,
    )
    expect(scss?.content).toBe(
      [
        '// Generated by scripts/mirror from shadcn base-vega/badge. Do not edit.',
        '//',
        '// Custom properties read here and set elsewhere (tokens, enclosing slots, inline styles):',
        '//   --primary',
        '//',
        '// Upstream classes with no CSS output, dropped:',
        '//   group/badge',
        '',
        ':where(.badge) {',
        '  display: inline-flex;',
        '  background-color: var(--primary);',
        '}',
        '',
      ].join('\n'),
    )
    expect(result.unresolved).toEqual({ badge: ['group/badge'] })
  })

  it('points registry dependencies and imports at mirrored items', async () => {
    const content = source('flex').replace(
      'import { cn } from "cn"',
      'import { cn } from "cn"\nimport { Badge as Base } from "@/registry/base-vega/ui/badge"',
    )
    const item = { ...badge(content), registryDependencies: ['badge'] }
    const { item: result } = await build(item)
    expect(result.registryDependencies).toEqual(['@bje/badge', '@bje/globals'])
  })

  it('wraps long property lists and omits empty sections', async () => {
    const properties = Array.from({ length: 12 }, (_, i) => `--a-long-custom-property-${i}`)
    const compile = async () =>
      `@layer utilities { .x { color: ${properties.map((p) => `var(${p})`).join(' ')}; } }`
    const [, scss] = (await build(badge(source('x')), compile)).files
    const comments = (scss?.content.split('\n') ?? []).filter((line) => line.startsWith('//'))
    expect(comments.filter((line) => line.startsWith('//   ')).length).toBeGreaterThan(1)
    expect(comments.every((line) => line.length <= 100)).toBe(true)
    expect(scss?.content).not.toContain('no CSS output')
  })

  it('converts what the shadcn CLI installs: icons and the heading font', async () => {
    const content = `import { cn } from "cn"
import { IconPlaceholder } from "@/app/(create)/components/icon-placeholder"
function Badge({ className }) {
  return (
    <span data-slot="badge" className={cn("cn-font-heading flex", className)}>
      <IconPlaceholder lucide="CheckIcon" tabler="IconCheck" className="cn-rtl-flip" />
    </span>
  )
}
export { Badge }`
    const result = await build(badge(content))
    const [tsx, scss] = result.files
    expect(tsx?.content).toContain('import { CheckIcon } from "lucide-react"')
    expect(tsx?.content).toContain('<CheckIcon />')
    // font-heading, which Tailwind inlines to the theme's --font-sans.
    expect(scss?.content).toContain('font-family: var(--font-sans);')
    expect(result.item.dependencies).toEqual(['clsx', 'lucide-react'])
  })

  it('lists the reason for each dropped rule in the header, and returns them', async () => {
    const built = await build(badge(source('flex [.border-b]:pb-4')))
    expect(built.files[1]?.content).toContain('// Dropped rules: consumer class')
    expect(built.dropped).toEqual(['consumer class'])
  })

  it('fails on a group or peer marker no mirrored element carries', async () => {
    await expect(build(badge(source('flex group-hover/missing:flex')))).rejects.toThrow(
      'needs a group/missing marker, which no mirrored element with a data-slot carries',
    )
  })

  it.each([
    ['a non-ui item', { ...badge('x'), type: 'registry:block' }, 'type registry:block'],
    [
      'a registry dependency that is not mirrored',
      { ...badge('x'), registryDependencies: ['button'] },
      'depends on button, which mirror.config.json does not list',
    ],
    [
      'a file without content',
      { ...badge('x'), files: [{ path: 'a', type: 'registry:ui' }] },
      'one file',
    ],
    ['no files', { ...badge('x'), files: [] }, 'one file'],
    [
      'several files',
      { ...badge('x'), files: [...badge('x').files, ...badge('y').files] },
      'one file',
    ],
  ])('rejects %s', async (_, item, message) => {
    await expect(build(item as UpstreamItem)).rejects.toThrow(message)
  })
})

