import { mkdir, mkdtemp, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { afterEach, beforeEach, describe, expect, it } from 'vitest'
import type { RegistryItem } from './component.ts'
import { forStyle } from './config.ts'
import {
  appendOverride,
  classesNamed,
  DARK_RULE,
  layerOverrides,
  listFiles,
  type Manifest,
  type Overrides,
  overridesDir,
  parseManifest,
  readOverrides,
  ruleSelectors,
} from './overrides.ts'
import { parsed } from './test-support.ts'

const config = forStyle(parsed, { name: 'frost', base: 'base-maia' })
const WHERE = 'registry/frost/overrides/overrides.json'

const generatedItem = (name: string, dir: string): RegistryItem => ({
  name,
  type: 'registry:ui',
  title: name,
  dependencies: [],
  devDependencies: [],
  registryDependencies: ['@bje/globals'],
  files: [{ path: `registry/frost/ui/${dir}/${dir}.tsx`, type: 'registry:ui' }],
})

const items = [generatedItem('popover', 'Popover'), generatedItem('card', 'Card')]

const addedItem = {
  name: 'frost-filter',
  type: 'registry:ui',
  title: 'Frost Filter',
  dependencies: [],
  devDependencies: [],
  registryDependencies: ['@bje/card'],
  files: [{ path: 'ui/FrostFilter/FrostFilter.tsx', type: 'registry:ui' }],
}

const manifest = (overrides: Partial<Record<keyof Manifest, unknown>> = {}) => ({
  items: [addedItem],
  registryDependencies: { popover: ['frost-filter'] },
  ...overrides,
})

const POPOVER = [
  '// Generated by scripts/mirror from shadcn base-maia/popover. Do not edit.',
  '',
  ':where(.popoverContent) {',
  '  color: red;',
  '}',
  '',
].join('\n')

// The generated files the build just wrote, by path.
const written = (files: Record<string, string>) => async (path: string) => files[path]

const overrides = (files: Record<string, string>, raw: unknown = manifest()): Overrides => ({
  dir: 'registry/frost/overrides',
  manifest: parseManifest(raw, WHERE),
  files: new Map(Object.entries(files)),
})

describe('overridesDir', () => {
  it("is the style's overrides directory, by path", () => {
    expect(overridesDir(config)).toBe('registry/frost/overrides')
  })
})

describe('parseManifest', () => {
  it('reads the items and the dependencies they add', () => {
    expect(parseManifest(manifest(), WHERE)).toEqual({
      items: [addedItem],
      registryDependencies: { popover: ['frost-filter'] },
    })
  })

  it('refuses items that are not an array', () => {
    expect(() => parseManifest(manifest({ items: {} }), WHERE)).toThrow(
      `${WHERE}: items must be an array`,
    )
  })

  it('refuses an item name that is not kebab-case', () => {
    expect(() =>
      parseManifest(manifest({ items: [{ ...addedItem, name: 'FrostFilter' }] }), WHERE),
    ).toThrow(`${WHERE}: items[0].name must be kebab-case`)
  })

  it('refuses an item without files', () => {
    expect(() => parseManifest(manifest({ items: [{ ...addedItem, files: [] }] }), WHERE)).toThrow(
      `${WHERE}: items[0].files must be a non-empty array`,
    )
  })

  it('refuses an item whose files are not an array', () => {
    expect(() =>
      parseManifest(manifest({ items: [{ ...addedItem, files: 'ui/FrostFilter' }] }), WHERE),
    ).toThrow(`${WHERE}: items[0].files must be a non-empty array`)
  })

  it('refuses an item type the catalog lacks', () => {
    expect(() =>
      parseManifest(manifest({ items: [{ ...addedItem, type: 'registry:block' }] }), WHERE),
    ).toThrow(`${WHERE}: items[0].type must be one of registry:ui, registry:hook, registry:file`)
  })

  it('refuses a file type the catalog lacks', () => {
    const files = [{ path: 'ui/FrostFilter/FrostFilter.tsx', type: 'registry:component' }]
    expect(() => parseManifest(manifest({ items: [{ ...addedItem, files }] }), WHERE)).toThrow(
      `${WHERE}: items[0].files[0].type must be one of registry:ui, registry:hook, registry:file`,
    )
  })

  it('refuses two items of one name', () => {
    const other = { ...addedItem, files: [{ path: 'ui/Other/Other.tsx', type: 'registry:ui' }] }
    expect(() => parseManifest(manifest({ items: [addedItem, other] }), WHERE)).toThrow(
      `${WHERE}: items must not repeat a name`,
    )
  })

  it('refuses one file in two items', () => {
    expect(() =>
      parseManifest(manifest({ items: [addedItem, { ...addedItem, name: 'lens' }] }), WHERE),
    ).toThrow(`${WHERE}: items must not repeat a file path`)
  })

  it('keeps a file target, and refuses a registry:file without one', () => {
    const file = { path: 'styles/frost.css', type: 'registry:file' }
    const target = '@components/styles/frost.css'
    expect(
      parseManifest(manifest({ items: [{ ...addedItem, files: [{ ...file, target }] }] }), WHERE)
        .items[0]?.files,
    ).toEqual([{ ...file, target }])
    expect(() =>
      parseManifest(manifest({ items: [{ ...addedItem, files: [file] }] }), WHERE),
    ).toThrow(`${WHERE}: items[0].files[0].target is required for registry:file`)
    expect(() =>
      parseManifest(
        manifest({ items: [{ ...addedItem, files: [{ ...file, target: 1 }] }] }),
        WHERE,
      ),
    ).toThrow(`${WHERE}: items[0].files[0].target must be a non-empty string`)
  })

  it('refuses dependencies that are not names', () => {
    expect(() =>
      parseManifest(manifest({ registryDependencies: { popover: 'frost-filter' } }), WHERE),
    ).toThrow(`${WHERE}: registryDependencies.popover must be an array`)
  })
})

describe('classesNamed', () => {
  it('names the module classes outside comments and :global()', () => {
    const scss = [
      '// .commented out',
      '/* .blocked',
      '   out */',
      ':where(:global(.dark) .popoverContent), .card > .cardTitle { width: 0.5rem; }',
    ].join('\n')
    expect([...classesNamed(scss)]).toEqual(['popoverContent', 'card', 'cardTitle'])
  })
})

describe('ruleSelectors', () => {
  it('lists every style rule, nested or in an at-rule, outside comments and keyframes', () => {
    const scss = [
      "@use 'sass:math';",
      '// .commented { }',
      ':where(.a), :where(.b:not(.c, .d)) {',
      '  color: red;',
      '  @supports (color: red) { .nested { color: red; } }',
      '  &[data-x] { color: blue; }',
      '}',
      '@media (width > 1px) { @supports (color: red) { .inMedia { color: red; } } }',
      '@keyframes spin { from { rotate: 0deg; } to { rotate: 1turn; } }',
      '@-webkit-keyframes spin { 50% { rotate: 0deg; } }',
      '.e > .f { color: red; }',
      '@container (width > 1px) { :where(.g) { color: red; } }',
      '@at-root .h:hover { color: red; }',
    ].join('\n')
    expect(ruleSelectors(scss)).toEqual([
      { selector: ':where(.a)', nested: false, direct: false },
      { selector: ':where(.b:not(.c, .d))', nested: false, direct: false },
      { selector: '.nested', nested: true, direct: false },
      { selector: '&[data-x]', nested: true, direct: true },
      { selector: '.inMedia', nested: false, direct: false },
      { selector: '.e > .f', nested: false, direct: false },
      { selector: ':where(.g)', nested: false, direct: false },
      { selector: '@at-root .h:hover', nested: false, direct: false },
    ])
  })
})

describe('appendOverride', () => {
  it('names the override under the generated header, then appends it', () => {
    expect(appendOverride('// Generated.\n\n.a {}\n', '.a { color: red; }\n', 'o/A.scss')).toBe(
      [
        '// Generated.',
        '// Ends with o/A.scss, appended by scripts/mirror.',
        '',
        '.a {}',
        '',
        '// Appended from o/A.scss.',
        '',
        '.a { color: red; }',
        '',
      ].join('\n'),
    )
  })
})

describe('layerOverrides', () => {
  it('appends stylesheets, adds the items and their dependencies, and leaves the input alone', async () => {
    const override = ':where(.popoverContent) { color: blue; }\n'
    const layered = await layerOverrides(
      overrides(
        {
          'ui/FrostFilter/FrostFilter.tsx': 'export {}\n',
          'ui/Popover/Popover.module.scss': override,
        },
        manifest({
          registryDependencies: { popover: ['frost-filter', 'card'], card: ['popover'] },
        }),
      ),
      config,
      items,
      written({ 'registry/frost/ui/Popover/Popover.module.scss': POPOVER }),
    )
    expect(layered.files).toEqual([
      { path: 'registry/frost/ui/FrostFilter/FrostFilter.tsx', content: 'export {}\n' },
      {
        path: 'registry/frost/ui/Popover/Popover.module.scss',
        content: appendOverride(
          POPOVER,
          override,
          'registry/frost/overrides/ui/Popover/Popover.module.scss',
        ),
      },
    ])
    expect(layered.dirs).toEqual(['registry/frost/ui/FrostFilter'])
    expect(layered.items.map((item) => [item.name, item.registryDependencies])).toEqual([
      ['popover', ['@bje/globals', '@bje/frost-filter', '@bje/card']],
      ['card', ['@bje/globals', '@bje/popover']],
      ['frost-filter', ['@bje/card']],
    ])
    expect(layered.items[2]?.files).toEqual([
      { path: 'registry/frost/ui/FrostFilter/FrostFilter.tsx', type: 'registry:ui' },
    ])
    expect(items[0]?.registryDependencies).toEqual(['@bje/globals'])
  })

  it('adds a dependency an item already has once', async () => {
    const layered = await layerOverrides(
      overrides(
        { 'ui/FrostFilter/FrostFilter.tsx': '' },
        manifest({ registryDependencies: { popover: ['globals', 'globals'] } }),
      ),
      config,
      [...items, generatedItem('globals', 'Globals')],
      written({}),
    )
    expect(layered.items[0]?.registryDependencies).toEqual(['@bje/globals'])
  })

  it('refuses an override of a component the style does not build', async () => {
    await expect(
      layerOverrides(
        overrides({ 'ui/FrostFilter/FrostFilter.tsx': '', 'ui/Nope/Nope.module.scss': '' }),
        config,
        items,
        written({}),
      ),
    ).rejects.toThrow(
      'registry/frost/overrides/ui/Nope/Nope.module.scss: no generated registry/frost/ui/Nope/Nope.module.scss to append to, and no item in overrides.json lists it',
    )
  })

  it('refuses an override that names a class the generated module lacks', async () => {
    await expect(
      layerOverrides(
        overrides({
          'ui/FrostFilter/FrostFilter.tsx': '',
          'ui/Popover/Popover.module.scss': ':where(.popoverContnet) { color: blue; }',
        }),
        config,
        items,
        written({ 'registry/frost/ui/Popover/Popover.module.scss': POPOVER }),
      ),
    ).rejects.toThrow(
      'registry/frost/overrides/ui/Popover/Popover.module.scss: .popoverContnet is not a class of registry/frost/ui/Popover/Popover.module.scss',
    )
  })

  it('refuses a module rule outside :where(), which outranks a className', async () => {
    for (const selector of [
      '.popoverContent',
      ':where(.popoverContent) > .popoverContent',
      ':where(.popoverContent',
    ]) {
      await expect(
        layerOverrides(
          overrides({
            'ui/FrostFilter/FrostFilter.tsx': '',
            'ui/Popover/Popover.module.scss': `:where(.popoverContent), ${selector} { color: blue; }`,
          }),
          config,
          items,
          written({ 'registry/frost/ui/Popover/Popover.module.scss': POPOVER }),
        ),
      ).rejects.toThrow(
        `registry/frost/overrides/ui/Popover/Popover.module.scss: ${selector} is not wrapped in :where()`,
      )
    }
  })

  it('refuses a module rule in an at-rule outside :where()', async () => {
    await expect(
      layerOverrides(
        overrides({
          'ui/FrostFilter/FrostFilter.tsx': '',
          'ui/Popover/Popover.module.scss':
            '@media (width > 1px) { .popoverContent { color: blue; } }',
        }),
        config,
        items,
        written({ 'registry/frost/ui/Popover/Popover.module.scss': POPOVER }),
      ),
    ).rejects.toThrow(
      'registry/frost/overrides/ui/Popover/Popover.module.scss: .popoverContent is not wrapped in :where()',
    )
  })

  it('refuses a block at-rule that emits rules unseen, such as @at-root', async () => {
    await expect(
      layerOverrides(
        overrides({
          'ui/FrostFilter/FrostFilter.tsx': '',
          'ui/Popover/Popover.module.scss':
            ':where(.popoverContent) { @at-root .popoverContent:hover { color: blue; } }',
        }),
        config,
        items,
        written({ 'registry/frost/ui/Popover/Popover.module.scss': POPOVER }),
      ),
    ).rejects.toThrow(
      'registry/frost/overrides/ui/Popover/Popover.module.scss: @at-root .popoverContent:hover is nested in a rule; write it as its own :where()',
    )
  })

  it('refuses a module rule nested in another, which compiles to a longer selector', async () => {
    await expect(
      layerOverrides(
        overrides({
          'ui/FrostFilter/FrostFilter.tsx': '',
          'ui/Popover/Popover.module.scss':
            ':where(.popoverContent) { @supports (color: red) { &:hover { color: blue; } } }',
        }),
        config,
        items,
        written({ 'registry/frost/ui/Popover/Popover.module.scss': POPOVER }),
      ),
    ).rejects.toThrow(
      'registry/frost/overrides/ui/Popover/Popover.module.scss: &:hover is nested in a rule; write it as its own :where()',
    )
  })

  it("allows maia's dark scope, nested directly in a :where() rule", async () => {
    const override = [
      ':where(.popoverContent) {',
      '  color: blue;',
      '  &:is(:global(.dark) *) {',
      '    @supports (color: red) { color: red; }',
      '  }',
      '}',
    ].join('\n')
    const layered = await layerOverrides(
      overrides({
        'ui/FrostFilter/FrostFilter.tsx': '',
        'ui/Popover/Popover.module.scss': override,
      }),
      config,
      items,
      written({ 'registry/frost/ui/Popover/Popover.module.scss': POPOVER }),
    )
    expect(layered.files.at(-1)?.content).toContain(DARK_RULE)
  })

  it('refuses the dark scope anywhere but directly in a :where() rule', async () => {
    for (const [override, selector] of [
      [
        `:where(.popoverContent) { @supports (color: red) { ${DARK_RULE} { color: red; } } }`,
        DARK_RULE,
      ],
      [`:where(.popoverContent) { ${DARK_RULE} { ${DARK_RULE} { color: red; } } }`, DARK_RULE],
      [`:where(.popoverContent) { ${DARK_RULE} { &:hover { color: red; } } }`, '&:hover'],
      [':where(.popoverContent) { &:is([data-dark] *) { color: red; } }', '&:is([data-dark] *)'],
      [`:where(.popoverContent) { ${DARK_RULE}:hover { color: red; } }`, `${DARK_RULE}:hover`],
      [
        `:where(.popoverContent) { ${DARK_RULE} .popoverContent { color: red; } }`,
        `${DARK_RULE} .popoverContent`,
      ],
      [
        ':where(.popoverContent) { &:is(:global(.dark) *, :global(.x) *) { color: red; } }',
        '&:is(:global(.dark) *, :global(.x) *)',
      ],
    ]) {
      await expect(
        layerOverrides(
          overrides({
            'ui/FrostFilter/FrostFilter.tsx': '',
            'ui/Popover/Popover.module.scss': override as string,
          }),
          config,
          items,
          written({ 'registry/frost/ui/Popover/Popover.module.scss': POPOVER }),
        ),
      ).rejects.toThrow(
        `registry/frost/overrides/ui/Popover/Popover.module.scss: ${selector} is nested in a rule; write it as its own :where()`,
      )
    }
  })

  it('appends to a global stylesheet without checking classes', async () => {
    const layered = await layerOverrides(
      overrides({ 'ui/FrostFilter/FrostFilter.tsx': '', 'styles/variables.scss': '.x {}' }),
      config,
      items,
      written({ 'registry/frost/styles/variables.scss': '// Generated.\n' }),
    )
    expect(layered.files.at(-1)?.content).toContain('.x {}')
  })

  it('refuses to append anything but a stylesheet', async () => {
    await expect(
      layerOverrides(
        overrides({ 'ui/FrostFilter/FrostFilter.tsx': '', 'ui/Popover/Popover.tsx': '' }),
        config,
        items,
        written({ 'registry/frost/ui/Popover/Popover.tsx': '' }),
      ),
    ).rejects.toThrow(
      'registry/frost/overrides/ui/Popover/Popover.tsx: only a stylesheet (.scss) appends to a generated file; list any other in overrides.json',
    )
  })

  it('refuses an item file the directory lacks', async () => {
    await expect(layerOverrides(overrides({}), config, items, written({}))).rejects.toThrow(
      `${WHERE}: items[0].files[0].path ui/FrostFilter/FrostFilter.tsx is not in registry/frost/overrides`,
    )
  })

  it('refuses an item a generated one already names', async () => {
    await expect(
      layerOverrides(
        overrides(
          { 'ui/FrostFilter/FrostFilter.tsx': '' },
          manifest({ items: [{ ...addedItem, name: 'card' }] }),
        ),
        config,
        items,
        written({}),
      ),
    ).rejects.toThrow(`${WHERE}: items[0].name card is a generated item`)
  })

  it("refuses an item in a generated item's directory", async () => {
    const file = { path: 'ui/Card/Extra.tsx', type: 'registry:ui' }
    await expect(
      layerOverrides(
        overrides(
          { 'ui/Card/Extra.tsx': '' },
          manifest({ items: [{ ...addedItem, files: [file] }] }),
        ),
        config,
        items,
        written({}),
      ),
    ).rejects.toThrow(`${WHERE}: registry/frost/ui/Card holds card, a generated item`)
  })

  it('refuses an item in a directory that holds generated items', async () => {
    for (const [path, dir] of [
      ['ui/Lens.tsx', 'registry/frost/ui'],
      ['Lens.tsx', 'registry/frost'],
    ] as const) {
      const file = { path, type: 'registry:ui' }
      await expect(
        layerOverrides(
          overrides({ [path]: '' }, manifest({ items: [{ ...addedItem, files: [file] }] })),
          config,
          items,
          written({}),
        ),
      ).rejects.toThrow(`${WHERE}: ${dir} holds popover, a generated item`)
    }
  })

  it('refuses an item in the overrides directory itself', async () => {
    const file = { path: 'overrides/Lens.tsx', type: 'registry:ui' }
    await expect(
      layerOverrides(
        overrides(
          { 'overrides/Lens.tsx': '' },
          manifest({ items: [{ ...addedItem, files: [file] }] }),
        ),
        config,
        items,
        written({}),
      ),
    ).rejects.toThrow(`${WHERE}: registry/frost/overrides/Lens.tsx is in registry/frost/overrides`)
  })

  it('refuses an item in a directory among the overrides', async () => {
    const file = { path: 'overrides/ui/Lens/Lens.tsx', type: 'registry:ui' }
    await expect(
      layerOverrides(
        overrides(
          { 'overrides/ui/Lens/Lens.tsx': '' },
          manifest({ items: [{ ...addedItem, files: [file] }] }),
        ),
        config,
        items,
        written({}),
      ),
    ).rejects.toThrow(
      `${WHERE}: registry/frost/overrides/ui/Lens/Lens.tsx is in registry/frost/overrides`,
    )
  })

  it('refuses a stylesheet appended to one among the overrides', async () => {
    const target = 'registry/frost/overrides/styles/variables.scss'
    await expect(
      layerOverrides(
        overrides({
          'ui/FrostFilter/FrostFilter.tsx': '',
          'overrides/styles/variables.scss': ':root {}',
        }),
        config,
        items,
        written({ [target]: ':root {}' }),
      ),
    ).rejects.toThrow(`${WHERE}: ${target} is in registry/frost/overrides`)
  })

  it('refuses an item file outside the directory', async () => {
    const file = { path: '../ui/Card/Card.tsx', type: 'registry:ui' }
    await expect(
      layerOverrides(
        overrides({}, manifest({ items: [{ ...addedItem, files: [file] }] })),
        config,
        items,
        written({}),
      ),
    ).rejects.toThrow(
      `${WHERE}: items[0].files[0].path ../ui/Card/Card.tsx is not in registry/frost/overrides`,
    )
  })

  it('refuses dependencies for an item the style lacks', async () => {
    await expect(
      layerOverrides(
        overrides(
          { 'ui/FrostFilter/FrostFilter.tsx': '' },
          manifest({ registryDependencies: { popovr: ['frost-filter'] } }),
        ),
        config,
        items,
        written({}),
      ),
    ).rejects.toThrow(`${WHERE}: registryDependencies.popovr is not an item of frost`)
  })

  it('refuses a dependency on an item the style lacks', async () => {
    await expect(
      layerOverrides(
        overrides(
          { 'ui/FrostFilter/FrostFilter.tsx': '' },
          manifest({ registryDependencies: { popover: ['frost-filtr'] } }),
        ),
        config,
        items,
        written({}),
      ),
    ).rejects.toThrow(
      `${WHERE}: registryDependencies.popover[0] frost-filtr is not an item of frost`,
    )
  })
})

